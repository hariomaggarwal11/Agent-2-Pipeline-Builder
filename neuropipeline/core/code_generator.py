def _build_model_prompt(description: str, dataset_info: dict) -> str:
    """Build the prompt for custom model generation.

    Parameters
    ----------
    description : str
        User's description of desired model.
    dataset_info : dict
        Dataset context.

    Returns
    -------
    str
        Complete prompt for Claude API.
    """
    modality = dataset_info.get("modality", "EEG")
    n_channels = dataset_info.get("n_channels", 14)
    n_classes = len(dataset_info.get("labels", [2]))
    fs = dataset_info.get("sampling_rate", 128)

    prompt = f"""Generate a complete PyTorch model class for the following:

Description: {description}

Context:
- Modality: {modality}
- Number of input channels: {n_channels}
- Number of output classes: {n_classes}
- Sampling rate: {fs} Hz

Requirements:
- Define as a PyTorch nn.Module subclass
- Include forward() method with proper input/output shapes documented
- Add weight initialization
- Include a get_model_summary() helper function
- The model should handle input shape: (batch_size, n_channels, sequence_length)
- Output shape: (batch_size, n_classes)

Return ONLY the Python code, no explanations."""

    return prompt


def _call_claude_api(prompt: str) -> str:
    """Call the Anthropic Claude API for code generation.

    Parameters
    ----------
    prompt : str
        The prompt to send to Claude.

    Returns
    -------
    str
        Generated code from Claude.
    """
    try:
        from anthropic import Anthropic

        client = Anthropic(api_key=ANTHROPIC_API_KEY)
        message = client.messages.create(
            model=ANTHROPIC_MODEL,
            max_tokens=ANTHROPIC_MAX_TOKENS,
            system=CODE_GEN_SYSTEM_PROMPT,
            messages=[{"role": "user", "content": prompt}],
        )

        # Extract text from response
        response_text = ""
        for block in message.content:
            if hasattr(block, "text"):
                response_text += block.text

        # Extract code block if present
        if "```python" in response_text:
            code_start = response_text.index("```python") + len("```python")
            code_end = response_text.index("```", code_start)
            return response_text[code_start:code_end].strip()
        elif "```" in response_text:
            code_start = response_text.index("```") + 3
            code_end = response_text.index("```", code_start)
            return response_text[code_start:code_end].strip()

        return response_text.strip()

    except ImportError:
        return _fallback_model_code(prompt)
    except Exception as e:
        return f"# Error calling Claude API: {e}\n# Falling back to template\n" + _fallback_model_code(prompt)


