"""Code Generator - Anthropic Claude API + Jinja2 template rendering."""

import os
import sys
from typing import Optional

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from config import (
    ANTHROPIC_API_KEY,
    ANTHROPIC_MODEL,
    ANTHROPIC_MAX_TOKENS,
    CODE_GEN_SYSTEM_PROMPT,
    TEMPLATE_REGISTRY,
)


def generate_stage_code(stage_name: str, config: dict, dataset_info: dict) -> str:
    """Generate Python code for a pipeline stage using templates.

    Attempts to use Jinja2 templates first. Falls back to inline code
    generation if template is not available.

    Parameters
    ----------
    stage_name : str
        Name of the pipeline stage (e.g., 'eeg_quality_check').
    config : dict
        Stage-specific configuration parameters.
    dataset_info : dict
        Dataset information from Agent 1 report.

    Returns
    -------
    str
        Generated Python code for the stage.
    """
    template_path = TEMPLATE_REGISTRY.get(stage_name)

    if template_path:
        # Try Jinja2 template rendering
        code = _render_template(template_path, config, dataset_info)
        if code:
            return code

    # Fall back to generating code from config
    return _generate_from_config(stage_name, config, dataset_info)


def generate_custom_model(description: str, dataset_info: dict) -> str:
    """Generate a custom model architecture via Claude API.

    Parameters
    ----------
    description : str
        Natural language description of the desired model architecture.
    dataset_info : dict
        Dataset information to inform the model design.

    Returns
    -------
    str
        Generated PyTorch model code.
    """
    prompt = _build_model_prompt(description, dataset_info)
    return _call_claude_api(prompt)


def _render_template(template_path: str, config: dict, dataset_info: dict) -> Optional[str]:
    """Render a Jinja2 template with the given config.

    Parameters
    ----------
    template_path : str
        Relative path to the template file.
    config : dict
        Configuration parameters for the template.
    dataset_info : dict
        Dataset information.

    Returns
    -------
    str or None
        Rendered code, or None if template not found.
    """
    try:
        from jinja2 import Environment, FileSystemLoader

        template_dir = os.path.join(os.path.dirname(__file__), "..", "templates")
        if not os.path.isdir(template_dir):
            return None

        # Get relative template path within templates directory
        rel_path = template_path.replace("templates/", "", 1)
        template_file = os.path.join(template_dir, rel_path)

        if not os.path.exists(template_file):
            return None

        env = Environment(
            loader=FileSystemLoader(template_dir),
            trim_blocks=True,
            lstrip_blocks=True,
        )
        template = env.get_template(rel_path)
        return template.render(config=config, dataset_info=dataset_info)

    except ImportError:
        return None
    except Exception:
        return None


